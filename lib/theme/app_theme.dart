import 'package:flutter/material.dart';

import '../generated/assets/fonts.gen.dart';

/// Raw color values for the Gauge R&R design system.
///
/// Widgets should use [AppPalette] tokens or [Theme] colors instead of
/// referencing these constants directly, so light and dark surfaces stay
/// consistent.
abstract final class AppColors {
  /// Brand palette swatches:
  static const Color lightTeal = Color(0xFFB2E2DF);
  static const Color softTeal = Color(0xFF67C5C1);
  static const Color teal = Color(0xFF1BA4A0);
  static const Color deepTeal = Color(0xFF167F7C);
  static const Color darkTeal = Color(0xFF105F5D);

  static const Color accent = darkTeal;

  static const Color success = deepTeal;
  static const Color warning = Color(0xFFB7791F);
  static const Color danger = Color(0xFFD64545);

  static const Color lightSurface = Color(0xFFF2F9F9);
  static const Color lightSurfaceRaised = Color(0xFFFFFFFF);
  static const Color lightBorder = Color(0xFFCCEBE9);
  static const Color lightTextPrimary = Color(0xFF0C2726);
  static const Color lightTextSecondary = Color(0xFF3D6664);

  static const Color darkSurface = Color(0xFF081C1B);
  static const Color darkSurfaceRaised = Color(0xFF0F2E2C);
  static const Color darkBorder = Color(0xFF184947);
  static const Color darkTextPrimary = Color(0xFFEAF7F6);
  static const Color darkTextSecondary = Color(0xFF86BDBA);
}

/// Semantic color tokens resolved for the current brightness.
@immutable
class AppPalette {
  const AppPalette({
    required this.surface,
    required this.surfaceRaised,
    required this.border,
    required this.textPrimary,
    required this.textSecondary,
    required this.accent,
    required this.success,
    required this.warning,
    required this.danger,
    this.lightTeal = AppColors.lightTeal,
    this.softTeal = AppColors.softTeal,
    this.teal = AppColors.teal,
    this.deepTeal = AppColors.deepTeal,
    this.darkTeal = AppColors.darkTeal,
  });

  static const AppPalette light = AppPalette(
    surface: AppColors.lightSurface,
    surfaceRaised: AppColors.lightSurfaceRaised,
    border: AppColors.lightBorder,
    textPrimary: AppColors.lightTextPrimary,
    textSecondary: AppColors.lightTextSecondary,
    accent: AppColors.darkTeal,
    success: AppColors.deepTeal,
    warning: AppColors.warning,
    danger: AppColors.danger,
  );

  static const AppPalette dark = AppPalette(
    surface: AppColors.darkSurface,
    surfaceRaised: AppColors.darkSurfaceRaised,
    border: AppColors.darkBorder,
    textPrimary: AppColors.darkTextPrimary,
    textSecondary: AppColors.darkTextSecondary,
    accent: AppColors.softTeal,
    success: AppColors.lightTeal,
    warning: AppColors.warning,
    danger: AppColors.danger,
  );

  /// Resolves the palette that matches the active [Theme].
  static AppPalette of(BuildContext context) {
    return Theme.of(context).brightness == Brightness.dark ? dark : light;
  }

  final Color surface;
  final Color surfaceRaised;
  final Color border;
  final Color textPrimary;
  final Color textSecondary;
  final Color accent;
  final Color success;
  final Color warning;
  final Color danger;

  final Color lightTeal;
  final Color softTeal;
  final Color teal;
  final Color deepTeal;
  final Color darkTeal;
}

/// Spacing scale used for padding, gaps, and layout rhythm.
abstract final class AppSpacing {
  static const double xxs = 2;
  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 24;
  static const double xxl = 32;
  static const double xxxl = 48;
}

/// Corner radius scale.
abstract final class AppRadius {
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 24;
}

/// Typography tokens. Colors are applied by widgets from [AppPalette] or the
/// active [Theme].
abstract final class AppTextStyles {
  /// Font family generated by FlutterGen.
  static const String fontFamily = FontFamily.pretendard;

  static const TextStyle display = TextStyle(
    fontFamily: fontFamily,
    fontSize: 28,
    height: 1.15,
    fontWeight: FontWeight.w700,
    letterSpacing: -0.4,
  );

  static const TextStyle title = TextStyle(
    fontFamily: fontFamily,
    fontSize: 20,
    height: 1.25,
    fontWeight: FontWeight.w700,
    letterSpacing: -0.2,
  );

  static const TextStyle sectionTitle = TextStyle(
    fontFamily: fontFamily,
    fontSize: 16,
    height: 1.3,
    fontWeight: FontWeight.w600,
  );

  static const TextStyle body = TextStyle(
    fontFamily: fontFamily,
    fontSize: 15,
    height: 1.45,
    fontWeight: FontWeight.w400,
  );

  static const TextStyle label = TextStyle(
    fontFamily: fontFamily,
    fontSize: 13,
    height: 1.3,
    fontWeight: FontWeight.w600,
    letterSpacing: 0.1,
  );

  static const TextStyle caption = TextStyle(
    fontFamily: fontFamily,
    fontSize: 13,
    height: 1.35,
    fontWeight: FontWeight.w400,
  );
}

/// Application-wide Material 3 theme configuration.
///
/// One builder produces both brightness variants so colors, typography and
/// component shapes stay consistent across the application.
abstract final class AppTheme {
  /// Default font family for the application.
  static const String fontFamily = AppTextStyles.fontFamily;

  static ThemeData light() => _build(Brightness.light);

  static ThemeData dark() => _build(Brightness.dark);

  static ThemeData _build(Brightness brightness) {
    final palette = brightness == Brightness.dark
        ? AppPalette.dark
        : AppPalette.light;

    final colorScheme =
        ColorScheme.fromSeed(
          seedColor: palette.accent,
          brightness: brightness,
        ).copyWith(
          primary: palette.accent,
          onPrimary: brightness == Brightness.dark
              ? const Color(0xFF081C1B)
              : Colors.white,
          surface: palette.surface,
          onSurface: palette.textPrimary,
          surfaceContainerHighest: palette.surfaceRaised,
          error: palette.danger,
          onError: Colors.white,
          outline: palette.border,
          outlineVariant: palette.border,
        );

    final base = ThemeData(
      useMaterial3: true,
      brightness: brightness,
      colorScheme: colorScheme,
      scaffoldBackgroundColor: palette.surface,
      fontFamily: fontFamily,
    );

    final textTheme = base.textTheme
        .apply(fontFamily: fontFamily)
        .copyWith(
          headlineMedium: AppTextStyles.display.copyWith(
            color: palette.textPrimary,
          ),
          titleLarge: AppTextStyles.title.copyWith(color: palette.textPrimary),
          titleMedium: AppTextStyles.sectionTitle.copyWith(
            color: palette.textPrimary,
          ),
          bodyLarge: AppTextStyles.body.copyWith(color: palette.textPrimary),
          bodyMedium: AppTextStyles.body.copyWith(color: palette.textPrimary),
          bodySmall: AppTextStyles.caption.copyWith(
            color: palette.textSecondary,
          ),
          labelLarge: AppTextStyles.label.copyWith(color: palette.textPrimary),
        );

    final roundedShape = RoundedRectangleBorder(
      borderRadius: BorderRadius.circular(AppRadius.md),
    );

    return base.copyWith(
      textTheme: textTheme,
      appBarTheme: AppBarTheme(
        backgroundColor: palette.surfaceRaised,
        foregroundColor: palette.textPrimary,
        elevation: 0,
        scrolledUnderElevation: 0,
        surfaceTintColor: Colors.transparent,
        centerTitle: false,
        titleTextStyle: AppTextStyles.title.copyWith(
          color: palette.textPrimary,
        ),
      ),
      cardTheme: CardThemeData(
        color: palette.surfaceRaised,
        surfaceTintColor: Colors.transparent,
        elevation: 0,
        margin: EdgeInsets.zero,
        shape: RoundedRectangleBorder(
          borderRadius: BorderRadius.circular(AppRadius.lg),
          side: BorderSide(color: palette.border),
        ),
      ),
      inputDecorationTheme: InputDecorationTheme(
        filled: true,
        fillColor: palette.surfaceRaised,
        contentPadding: const EdgeInsets.symmetric(
          horizontal: AppSpacing.lg,
          vertical: AppSpacing.md,
        ),
        border: OutlineInputBorder(
          borderRadius: BorderRadius.circular(AppRadius.md),
          borderSide: BorderSide(color: palette.border),
        ),
        enabledBorder: OutlineInputBorder(
          borderRadius: BorderRadius.circular(AppRadius.md),
          borderSide: BorderSide(color: palette.border),
        ),
        focusedBorder: OutlineInputBorder(
          borderRadius: BorderRadius.circular(AppRadius.md),
          borderSide: BorderSide(color: palette.accent, width: 1.6),
        ),
        errorBorder: OutlineInputBorder(
          borderRadius: BorderRadius.circular(AppRadius.md),
          borderSide: BorderSide(color: palette.danger),
        ),
        focusedErrorBorder: OutlineInputBorder(
          borderRadius: BorderRadius.circular(AppRadius.md),
          borderSide: BorderSide(color: palette.danger, width: 1.6),
        ),
        labelStyle: AppTextStyles.label.copyWith(color: palette.textSecondary),
        hintStyle: AppTextStyles.body.copyWith(
          color: palette.textSecondary.withValues(alpha: 0.8),
        ),
        helperStyle: AppTextStyles.caption.copyWith(
          color: palette.textSecondary,
        ),
        errorStyle: AppTextStyles.caption.copyWith(color: palette.danger),
      ),
      filledButtonTheme: FilledButtonThemeData(
        style: FilledButton.styleFrom(
          minimumSize: const Size(0, 48),
          shape: roundedShape,
          textStyle: AppTextStyles.sectionTitle,
        ),
      ),
      outlinedButtonTheme: OutlinedButtonThemeData(
        style: OutlinedButton.styleFrom(
          minimumSize: const Size(0, 48),
          shape: roundedShape,
          side: BorderSide(color: palette.border),
          textStyle: AppTextStyles.sectionTitle,
        ),
      ),
      textButtonTheme: TextButtonThemeData(
        style: TextButton.styleFrom(
          shape: roundedShape,
          textStyle: AppTextStyles.sectionTitle,
        ),
      ),
      listTileTheme: ListTileThemeData(
        iconColor: palette.accent,
        textColor: palette.textPrimary,
      ),
      dividerTheme: DividerThemeData(color: palette.border, thickness: 1),
      snackBarTheme: SnackBarThemeData(
        behavior: SnackBarBehavior.floating,
        backgroundColor: palette.textPrimary,
        contentTextStyle: AppTextStyles.body.copyWith(
          color: palette.surfaceRaised,
        ),
        shape: RoundedRectangleBorder(
          borderRadius: BorderRadius.circular(AppRadius.md),
        ),
      ),
    );
  }
}
